import assert from 'node:assert/strict';
import {createLocalGigaamPipeline} from '/app/core/meetings/services/bot/dist/local-gigaam-pipeline.js';
const epoch = 1700000000000, rate = 16000;
const speech = seconds => new Float32Array(seconds * rate).fill(0.25);
let calls = [], segments = [], errors = [], active = 0, peak = 0;
let pipeline = createLocalGigaamPipeline(async pcm => {
  active++; peak = Math.max(peak, active); calls.push(pcm);
  await new Promise(resolve => setTimeout(resolve, 5)); active--;
  return {text:'known speech',language:'ru',segments:[],duration:pcm.length/rate};
}, {publish:async segment=>segments.push(segment)},error=>errors.push(error));
pipeline.feedMixedAudio(speech(45),epoch);
await pipeline.stop();
assert.deepEqual(calls.map(p=>p.length),[20*rate,20*rate,5*rate]);
assert.equal(peak,1); assert.equal(errors.length,0);
assert.equal(calls.reduce((n,p)=>n+p.length,0),45*rate);
assert.deepEqual(segments.map(s=>[s.start,s.end]),[[epoch/1000,epoch/1000+20],[epoch/1000+20,epoch/1000+40],[epoch/1000+40,epoch/1000+45]]);
assert.ok(segments.every(s=>s.completed&&s.speaker===''));
pipeline.feedMixedAudio(speech(1),epoch+21000); assert.equal(calls.length,3);
console.log('PASS: PCM retained, twenty-second windows, serialized inference, timestamps, terminal flush');
calls=[]; segments=[];
pipeline=createLocalGigaamPipeline(async pcm=>{calls.push(pcm); return {text:'speech',segments:[]};},{publish:async s=>segments.push(s)});
pipeline.feedMixedAudio(new Float32Array(10*rate),epoch);
assert.equal(calls.length,0);
pipeline.feedMixedAudio(speech(2),epoch+10000);
await new Promise(resolve=>setTimeout(resolve,1550));
assert.equal(calls.length,1);
pipeline.feedMixedAudio(speech(1),epoch+14000);
await pipeline.stop();
assert.equal(calls.length,2); assert.equal(segments.length,2);
console.log('PASS: leading silence skipped, short phrase flushes on pause, next phrase survives');
calls=[]; errors=[];
pipeline=createLocalGigaamPipeline(async pcm=>{calls.push(pcm); if(calls.length===1)throw Error('test inference outage'); return {text:'recovered',segments:[]};},{publish:async()=>{}},error=>errors.push(error));
pipeline.feedMixedAudio(speech(40),epoch); await pipeline.stop();
assert.equal(errors.length,1); assert.equal(calls.length,2);
console.log('PASS: inference failure reported, subsequent audio processed');
calls=[]; segments=[];
pipeline=createLocalGigaamPipeline(async pcm=>{calls.push(pcm);return {text:'quiet phrase',segments:[]};},{publish:async s=>segments.push(s)});
pipeline.feedMixedAudio(new Float32Array(rate).fill(0.001),epoch);
pipeline.feedMixedAudio(new Float32Array(rate).fill(0.001),epoch+5000);
await pipeline.stop(); await pipeline.stop();
assert.equal(calls.length,2);
assert.deepEqual(segments.map(s=>[s.start,s.end]),[[epoch/1000,epoch/1000+1],[epoch/1000+5,epoch/1000+6]]);
console.log('PASS: quiet speech retained, capture gap not compressed, stop is idempotent');
calls=[]; errors=[];
let release;
const gate=new Promise(resolve=>{release=resolve;});
pipeline=createLocalGigaamPipeline(async pcm=>{calls.push(pcm);await gate;return {text:'queued phrase',segments:[]};},{publish:async()=>{}},error=>errors.push(error));
pipeline.feedMixedAudio(speech(100),epoch);
pipeline.feedMixedAudio(speech(1),epoch+100000);
assert.equal(errors.length,1,'overload must be visible without flooding the fault observer');
release(); await pipeline.stop();
assert.equal(calls.length,4,'queue must bound retained PCM/inference work');
console.log('PASS: overload bounded and reported, accepted windows drain on stop');
